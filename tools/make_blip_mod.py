"""Package the Blip art (helper-art/blaster-helper) as a native-runtime mod.

Run with a Python that has Pillow. Writes mods/blip/{mod.txt,body.bin,bolt.bin}
and mods/mods.list. Pose values are the native helper pose word $40:043A,
measured in the native runtime (see NATIVE-EXPERIMENT.md / pose_research.py).
"""
import json
from pathlib import Path
from PIL import Image

ART = Path('/Users/markrogers/kss-work/helper-art/blaster-helper')
OUT = Path(__file__).resolve().parents[1] / 'mods'
BODY = ['idle0', 'idle1', 'walk0', 'walk1', 'walk2', 'walk3', 'jump', 'fall', 'attack0', 'attack1', 'hurt']
BOLT = ['bolt0', 'bolt1']


def raw(names, size):
    blob = bytearray()
    for n in names:
        im = Image.open(ART / 'frames' / f'{n}.png')
        assert im.mode == 'P' and im.size == (size, size), (n, im.mode, im.size)
        blob += bytes(im.get_flattened_data() if hasattr(im, 'get_flattened_data') else im.getdata())
    return bytes(blob)


def bgr555(hex_color):
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return (r >> 3) | (g >> 3) << 5 | (b >> 3) << 10


def main():
    d = OUT / 'blip'; d.mkdir(parents=True, exist_ok=True)
    (d / 'body.bin').write_bytes(raw(BODY, 32))
    (d / 'bolt.bin').write_bytes(raw(BOLT, 16))
    colors = json.loads((ART / 'palette.json').read_text())['colors']
    words = ' '.join(f'{bgr555(c):04X}' for c in colors[1:16])
    helper_live = """when 0x2C00 == 0x4B48      # helper form state valid (ROM hack BW-RAM)
when 0x2C02 == 1           # helper form = Blaster
when 0x0240 in 2 3         # slot 04 is a live helper"""
    text = f"""# Blip: custom Blaster helper art for the independent Blaster helper.
# Generated by tools/make_blip_mod.py from helper-art/blaster-helper.

rule actor blip-body
{helper_live}
match palette 2 tiles 0x20 0x3F    # native helper body objects
art body.bin 32 32 {' '.join(BODY)}
palette 2 {words}
actor 0x0896 0x0910 0x135E 0x1360 0x043A   # helper X, Y, camera X, Y, pose
anchor 16 17
anim idle 30:idle0 30:idle1
anim walk 6:walk0 6:walk1 6:walk2 6:walk3
anim jump 0:jump
anim fall 0:fall
anim attack 6:attack0 0:attack1
anim aim 0:attack0
anim hurt 0:hurt
pose idle 0x58 0x3A 0x5E 0x36
pose walk 0x64 0x66 0x68 0x6A 0x4C
pose jump 0x6C
pose fall 0x6E 0x48
pose attack 0x86 0x88 0x8A 0x8C 0x8E 0x96 0x98 0x9E
pose aim 0x90 0xA2
pose hurt 0x24 0x26 0x28 0x2A
default idle

rule object blip-bolt
{helper_live}
match palette 1 tiles 0x48 0x4F    # helper FX page (helper-owned shots)
art bolt.bin 16 16 {' '.join(BOLT)}
anim shimmer 4:bolt0 4:bolt1
play shimmer
"""
    (d / 'mod.txt').write_text(text)
    (OUT / 'mods.list').write_text('blip\n')
    print(d, len((d / 'body.bin').read_bytes()), len((d / 'bolt.bin').read_bytes()))


if __name__ == '__main__':
    main()
